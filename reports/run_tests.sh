#!/bin/bash

# ==============================================================
#  run_tests.sh — сборка и запуск тестов
#  Использование:  ./run_tests.sh
# ==============================================================

set -u

# --- Настройки ---
TEST_SRC="tests/test_main.cpp"
TEST_BIN="tests/tests"

# --- Цвета (если терминал поддерживает) ---
GREEN="\033[0;32m"
RED="\033[0;31m"
YELLOW="\033[1;33m"
NC="\033[0m"

echo "=============================================="
echo " СБОРКА ТЕСТОВ"
echo "=============================================="

# --- Проверка, что файл тестов существует ---
if [ ! -f "$TEST_SRC" ]; then
    echo -e "${RED}Ошибка: файл '$TEST_SRC' не найден!${NC}"
    exit 1
fi

# --- Компиляция ---
# ВАЖНО: НЕ используем -DNDEBUG, иначе assert() будет отключён
g++ -std=c++11 -Wall -Wextra "$TEST_SRC" -o "$TEST_BIN"

if [ $? -ne 0 ]; then
    echo -e "${RED}Ошибка компиляции!${NC}"
    exit 1
fi

echo -e "${GREEN}Компиляция успешна.${NC}"
echo

# --- Запуск тестов ---
echo "=============================================="
echo " ЗАПУСК ТЕСТОВ"
echo "=============================================="

"$TEST_BIN"
RESULT=$?

echo
echo "=============================================="
if [ $RESULT -eq 0 ]; then
    echo -e "${GREEN}РЕЗУЛЬТАТ: ВСЕ ТЕСТЫ ПРОЙДЕНЫ${NC}"
    echo "=============================================="
    exit 0
else
    echo -e "${RED}РЕЗУЛЬТАТ: ТЕСТЫ ПРОВАЛЕНЫ (код возврата: $RESULT)${NC}"
    echo "=============================================="
    exit 1
fi