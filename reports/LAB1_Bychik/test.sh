#!/bin/bash

set -u

# ---------- Настройки ----------
SRC="кпо1.26.cpp"
BIN="./game_test"
BUILD_LOG="build.log"

PASS=0
FAIL=0

# ---------- Сборка ----------
echo "=== Сборка проекта ==="
g++ -std=c++17 -Wall -o "$BIN" "$SRC" 2> "$BUILD_LOG"

if [ $? -ne 0 ]; then
    echo "[ОШИБКА] Компиляция не удалась. Лог:"
    cat "$BUILD_LOG"
    exit 1
fi
echo "Сборка успешна."
echo

# ---------- Вспомогательная функция ----------
# $1 — имя теста
# $2 — входные данные (можно с \n)
# $3 — ожидаемая подстрока в выводе
run_test() {
    local name="$1"
    local input="$2"
    local expected="$3"

    echo "--- Тест: $name ---"

    # printf интерпретирует \n как перевод строки, echo -e не везде работает
    output=$(printf "%b" "$input" | "$BIN" 2>&1)

    if echo "$output" | grep -qF "$expected"; then
        echo "[OK]   Найдено: $expected"
        PASS=$((PASS+1))
    else
        echo "[FAIL] Не найдено: $expected"
        echo "       Первые строки вывода:"
        echo "$output" | head -5 | sed 's/^/       /'
        FAIL=$((FAIL+1))
    fi
    echo
}

# 1. Выход из главного меню
run_test "Выход из главного меню" \
    "5\n" \
    "Выход из программы"

# 2. Запуск игры
run_test "Пункт 1 — Начать игру" \
    "1\n\n5\n" \
    "Начало игры"

# 3. Загрузка игры
run_test "Пункт 2 — Загрузить игру" \
    "2\n\n5\n" \
    "Функция загрузки пока недоступна"

# 4. О программе
run_test "Пункт 4 — О программе" \
    "4\n\n5\n" \
    "О программе"

# 5. Открытие настроек
run_test "Пункт 3 — Открытие настроек" \
    "3\n4\n5\n" \
    "Настройки"

# 6. Изменение специальности
run_test "Изменение специальности" \
    "3\n1\nФизика\n4\n5\n" \
    "Физика"

# 7. Изменение имени студента
run_test "Изменение имени студента" \
    "3\n2\nАлексей\n4\n5\n" \
    "Алексей"

# 8. Изменение количества предметов
run_test "Изменение количества предметов" \
    "3\n3\n7\n4\n5\n" \
    "7"

# 9. Некорректный ввод в главном меню
run_test "Некорректный ввод (буквы)" \
    "abc\n5\n" \
    "Некорректный ввод"

# 10. Отрицательное количество предметов
run_test "Отрицательное количество предметов" \
    "3\n3\n-1\n4\n5\n" \
    "Некорректное значение"

# 11. Ноль предметов
run_test "Ноль предметов" \
    "3\n3\n0\n4\n5\n" \
    "Некорректное значение"

# 12. Несуществующий пункт меню
run_test "Несуществующий пункт меню" \
    "99\n5\n" \
    "Такого пункта нет"

echo "======================================"
echo "Пройдено: $PASS"
echo "Провалено: $FAIL"
echo "======================================"

# Убрать временный бинарник
rm -f "$BIN" "$BUILD_LOG"

if [ "$FAIL" -eq 0 ]; then
    exit 0
else
    exit 1
fi
