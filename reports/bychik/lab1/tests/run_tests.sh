#!/bin/bash

# Выходим при любой ошибке (чтобы CI покраснел, если что-то не так)
set -e 

echo "======================================"
echo " 1. Проверка компиляции main.cpp"
echo "======================================"
g++ -std=c++17 -Wall -o ./tests/main_check src/main.cpp
if [ $? -eq 0 ]; then
    echo "[OK] Основная программа успешно компилируется."
else
    echo "[FAIL] Ошибка компиляции main.cpp!"
    exit 1
fi

echo -e "\n======================================"
echo " 2. Сборка и запуск тестов"
echo "======================================"
g++ -std=c++17 -Wall -o ./tests/test_runner tests/test_solution.cpp
./tests/test_runner

echo -e "\n======================================"
echo " Все проверки успешно пройдены!"
echo "======================================"

# Очищаем за собой временные файлы (чтобы не мусорить в репозитории)
rm -f ./tests/main_check ./tests/test_runner
